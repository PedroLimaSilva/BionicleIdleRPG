/** Six Rahkshi powers, cycling for the post–Mask of Light gauntlet. */
const RAHKSHI_GAUNTLET_ROTATION: KraataPower[] = [
  KraataPower.Fragmentation,
  KraataPower.Disintegration,
  KraataPower.Poison,
  KraataPower.Fear,
  KraataPower.Hunger,
  KraataPower.Anger,
];

function makeRahkshiKraataGauntletWaves(): Array<{ id: string; lvl: number }[]> {
  const waves: Array<{ id: string; lvl: number }[]> = [];
  const len = RAHKSHI_GAUNTLET_ROTATION.length;
  for (let i = 0; i < 100; i++) {
    const prev = RAHKSHI_GAUNTLET_ROTATION[(i - 1 + len) % len];
    const curr = RAHKSHI_GAUNTLET_ROTATION[i % len];
    const next = RAHKSHI_GAUNTLET_ROTATION[(i + 1) % len];
    waves.push([
      { id: prev, lvl: 1 },
      { id: curr, lvl: 1 },
      { id: next, lvl: 1 },
    ]);
  }
  return waves;
}

